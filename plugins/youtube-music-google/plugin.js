// YouTube Music for Helix, through the official YouTube Data API v3 only.
//
// What it does: search, your playlists, your liked songs, and the albums
// behind them, so Helix Server can find its own copies. Play opens the
// YouTube Music app. It never touches YouTube's audio or video streams and
// never calls YouTube's internal endpoints.

var API = "https://www.googleapis.com/youtube/v3/";
var MUSIC = "https://music.youtube.com/";

function get(path, query) {
  var r = helix.fetch(API + path, { query: query, auth: true });
  var body = null;
  try { body = r.json(); } catch (e) {}
  if (!r.ok) {
    var msg = body && body.error && body.error.message ? body.error.message : "HTTP " + r.status;
    var reason = body && body.error && body.error.errors && body.error.errors[0] ? body.error.errors[0].reason : "";
    if (reason === "quotaExceeded" || reason === "dailyLimitExceeded") {
      msg = "YouTube's daily quota for this server is used up; it resets at midnight Pacific time";
    }
    throw new Error("YouTube: " + msg);
  }
  return body || {};
}

// pages follows nextPageToken up to max pages.
function pages(path, query, max) {
  var items = [];
  var token = "";
  for (var i = 0; i < max; i++) {
    var q = {};
    for (var k in query) q[k] = query[k];
    if (token) q.pageToken = token;
    var res = get(path, q);
    items = items.concat(res.items || []);
    token = res.nextPageToken || "";
    if (!token) break;
  }
  return items;
}

function thumb(sn) {
  var t = (sn && sn.thumbnails) || {};
  var best = t.maxres || t.standard || t.high || t.medium || t["default"];
  return best ? best.url : "";
}

function topicArtist(channel) {
  channel = channel || "";
  var m = channel.match(/^(.*) - Topic$/);
  return m ? m[1] : "";
}

function albumTitle(title) {
  return (title || "").replace(/^Album - /, "");
}

// durationMs reads ISO 8601 "PT1H2M3S".
function durationMs(iso) {
  var m = /^P(?:(\d+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/.exec(iso || "");
  if (!m) return 0;
  return ((+(m[1] || 0) * 24 + +(m[2] || 0)) * 3600 + +(m[3] || 0) * 60 + +(m[4] || 0)) * 1000;
}

// autoGenerated reads the description YouTube writes for a label's upload:
//
//   Provided to YouTube by <label>
//
//   <song> · <artist> · <artist>
//
//   <album>
//
//   ℗ 2019 <label>
//
//   Released on: 2019-05-03
function autoGenerated(desc) {
  if (!desc || desc.indexOf("Provided to YouTube by") !== 0) return null;
  var paras = desc.split(/\n\s*\n/).map(function (p) { return p.trim(); });
  if (paras.length < 3) return null;
  var parts = paras[1].split(" · ");
  if (parts.length < 2) return null;
  var out = { title: parts[0], artist: parts[1], album: paras[2], year: 0 };
  var rel = /Released on: (\d{4})/.exec(desc) || /℗ (\d{4})/.exec(desc);
  if (rel) out.year = +rel[1];
  return out;
}

function splitTitle(title, channel) {
  var artist = topicArtist(channel);
  if (artist) return { artist: artist, title: title };
  var m = /^(.+?) - (.+)$/.exec(title || "");
  if (m) return { artist: m[1], title: m[2].replace(/\s*[\(\[](official|lyric|audio|music video|video)[^\)\]]*[\)\]]\s*/gi, " ").trim() };
  return { artist: channel || "", title: title };
}

function trackFromVideo(v) {
  var sn = v.snippet || {};
  var id = typeof v.id === "string" ? v.id : (v.id && v.id.videoId) || (v.contentDetails && v.contentDetails.videoId) || "";
  var ag = autoGenerated(sn.description);
  var st = splitTitle(sn.title, sn.videoOwnerChannelTitle || sn.channelTitle);
  return {
    id: id,
    title: ag ? ag.title : st.title,
    artist: ag ? ag.artist : st.artist,
    album: ag ? ag.album : "",
    year: ag ? ag.year : 0, // read by album(); not part of a track
    durationMs: durationMs(v.contentDetails && v.contentDetails.duration),
    coverUrl: thumb(sn),
    openUrl: MUSIC + "watch?v=" + encodeURIComponent(id)
  };
}

// videos reads full video records (duration, description) 50 at a time.
function videos(ids) {
  var out = {};
  for (var i = 0; i < ids.length; i += 50) {
    var res = get("videos", { part: "snippet,contentDetails", id: ids.slice(i, i + 50).join(","), maxResults: 50 });
    (res.items || []).forEach(function (v) { out[v.id] = v; });
  }
  return out;
}

// itemsToTracks turns playlist items into tracks, reading durations.
function itemsToTracks(items) {
  var ids = items.map(function (it) { return it.contentDetails && it.contentDetails.videoId; }).filter(Boolean);
  var full = videos(ids);
  var tracks = [];
  items.forEach(function (it, i) {
    var vid = it.contentDetails && it.contentDetails.videoId;
    if (!vid) return;
    var v = full[vid];
    // A deleted or private video has an item and no record.
    if (!v) return;
    var t = trackFromVideo(v);
    t.number = (it.snippet && typeof it.snippet.position === "number" ? it.snippet.position : i) + 1;
    tracks.push(t);
  });
  return tracks;
}

exports.account = function () {
  var res = get("channels", { part: "snippet", mine: "true" });
  var ch = (res.items || [])[0];
  return { name: ch ? ch.snippet.title : "" };
};

exports.search = function (q) {
  var query = { part: "snippet", q: q, maxResults: 20, type: "playlist" };
  if (helix.settings.region) query.regionCode = helix.settings.region;
  var out = { albums: [], tracks: [], artists: [], playlists: [] };
  (get("search", query).items || []).forEach(function (it) {
    var sn = it.snippet || {};
    var id = it.id && it.id.playlistId;
    if (!id) return;
    var artist = topicArtist(sn.channelTitle);
    // Albums are the playlists YouTube makes for a release, on the
    // artist's "- Topic" channel; anything else is somebody's playlist.
    if (artist || /^Album - /.test(sn.title)) {
      out.albums.push({ id: id, title: albumTitle(sn.title), artist: artist || sn.channelTitle,
        coverUrl: thumb(sn), openUrl: MUSIC + "playlist?list=" + encodeURIComponent(id) });
    } else {
      out.playlists.push({ id: id, title: sn.title, owner: sn.channelTitle, coverUrl: thumb(sn),
        openUrl: MUSIC + "playlist?list=" + encodeURIComponent(id) });
    }
  });
  if (helix.settings.searchSongs !== false) {
    var sq = { part: "snippet", q: q, maxResults: 20, type: "video", videoCategoryId: "10" };
    if (helix.settings.region) sq.regionCode = helix.settings.region;
    (get("search", sq).items || []).forEach(function (it) {
      var sn = it.snippet || {};
      var id = it.id && it.id.videoId;
      if (!id) return;
      var st = splitTitle(sn.title, sn.channelTitle);
      out.tracks.push({ id: id, title: st.title, artist: st.artist, coverUrl: thumb(sn),
        openUrl: MUSIC + "watch?v=" + encodeURIComponent(id) });
    });
  }
  return out;
};

exports.album = function (id) {
  // A library album is named after one of its songs ("v:<videoId>"): the
  // Data API does not say which release playlist a song belongs to.
  if (id.indexOf("v:") === 0) {
    var vid = id.slice(2);
    var v = videos([vid])[vid];
    if (!v) throw new Error("YouTube: that song is no longer available");
    var ag = autoGenerated(v.snippet.description) || {};
    var t = trackFromVideo(v);
    t.number = 1;
    return { id: id, title: ag.album || t.title, artist: ag.artist || t.artist, year: ag.year || 0,
      coverUrl: t.coverUrl, tracks: [t],
      openUrl: MUSIC + "search?q=" + encodeURIComponent((ag.artist || t.artist) + " " + (ag.album || t.title)) };
  }
  var res = get("playlists", { part: "snippet,contentDetails", id: id });
  var pl = (res.items || [])[0];
  if (!pl) throw new Error("YouTube: that album is not available");
  var tracks = itemsToTracks(pages("playlistItems", { part: "snippet,contentDetails", playlistId: id, maxResults: 50 }, 4));
  // The year lives in the songs' descriptions, not the playlist's.
  var year = tracks.length ? tracks[0].year : 0;
  return {
    id: id,
    title: albumTitle(pl.snippet.title),
    artist: topicArtist(pl.snippet.channelTitle) || (tracks[0] && tracks[0].artist) || pl.snippet.channelTitle,
    year: year,
    trackCount: pl.contentDetails ? pl.contentDetails.itemCount : tracks.length,
    coverUrl: thumb(pl.snippet),
    openUrl: MUSIC + "playlist?list=" + encodeURIComponent(id),
    tracks: tracks
  };
};

function likedMusic(maxPages) {
  return pages("videos", { part: "snippet,contentDetails", myRating: "like", maxResults: 50 }, maxPages)
    .filter(function (v) { return v.snippet && v.snippet.categoryId === "10"; });
}

exports.playlists = function () {
  var out = [{ id: "liked", title: "Liked music", owner: "You", openUrl: MUSIC + "playlist?list=LM" }];
  pages("playlists", { part: "snippet,contentDetails", mine: "true", maxResults: 50 }, 4).forEach(function (pl) {
    out.push({ id: pl.id, title: pl.snippet.title, owner: pl.snippet.channelTitle,
      trackCount: pl.contentDetails ? pl.contentDetails.itemCount : 0, coverUrl: thumb(pl.snippet),
      openUrl: MUSIC + "playlist?list=" + encodeURIComponent(pl.id) });
  });
  return out;
};

exports.playlist = function (id) {
  if (id === "liked") {
    var tracks = likedMusic(4).map(function (v, i) { var t = trackFromVideo(v); t.number = i + 1; return t; });
    return { id: "liked", title: "Liked music", owner: "You", openUrl: MUSIC + "playlist?list=LM", tracks: tracks };
  }
  var res = get("playlists", { part: "snippet,contentDetails", id: id });
  var pl = (res.items || [])[0];
  if (!pl) throw new Error("YouTube: that playlist is not available");
  return {
    id: id, title: pl.snippet.title, owner: pl.snippet.channelTitle, coverUrl: thumb(pl.snippet),
    openUrl: MUSIC + "playlist?list=" + encodeURIComponent(id),
    tracks: itemsToTracks(pages("playlistItems", { part: "snippet,contentDetails", playlistId: id, maxResults: 50 }, 4))
  };
};

// library is the albums behind your liked songs. Only songs a label
// uploaded say which album they are on; the rest come back as songs.
exports.library = function () {
  var albums = {};
  var order = [];
  var tracks = [];
  likedMusic(10).forEach(function (v) {
    var t = trackFromVideo(v);
    tracks.push(t);
    var ag = autoGenerated(v.snippet.description);
    if (!ag || !ag.album) return;
    var key = (ag.artist + "\u0000" + ag.album).toLowerCase();
    if (!albums[key]) {
      albums[key] = { id: "v:" + v.id, title: ag.album, artist: ag.artist, year: ag.year, coverUrl: t.coverUrl,
        openUrl: MUSIC + "search?q=" + encodeURIComponent(ag.artist + " " + ag.album) };
      order.push(key);
    }
  });
  return { albums: order.map(function (k) { return albums[k]; }), tracks: tracks };
};
